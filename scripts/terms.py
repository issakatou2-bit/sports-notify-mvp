#!/usr/bin/env python3
"""
指標や用語の、一行の説明。

なぜ要るのか:
  資産動画は実測で維持率76.3%と、日次の倍以上まで見られている。
  そこを見ているのは、野球やサッカーを知り始めた層だと考えている。
  その人たちにとって「OPS.929」は数字ですらない。

  clutch.py が場面の説明(サヨナラ＝最終回裏に…)を持っていて、
  同じ形を指標にも広げる。読み上げは足さない。画面の下に小さく
  出すだけにする。読み上げに入れると、毎回同じ説明を聞かされる。

使い方(他のスクリプトから):
  import terms
  terms.note_for("今シーズンは126試合、打率.281、OPS.929")
  -> "OPS＝出塁率＋長打率。打者の総合力を1つの数字で見る"
"""

# 画面に出す一行。長いものは入らないので、40字を目安にしてある。
#
# 説明そのものは用語集(web/glossary.html)と揃える。別々に書くと、
# 同じ言葉が2か所で違う説明を持つことになる。
NOTES = {
    "OPS": "OPS＝出塁率＋長打率。打者の総合力を1つの数字で",
    "防御率": "防御率＝9イニングあたりの自責点。低いほど良い",
    "WHIP": "WHIP＝1イニングあたりに出す走者の数",
    "自責": "自責点＝投手の責任になる失点。失策絡みは除く",
    "奪三振": "奪三振＝投手が三振を取った数",
    "打点": "打点＝その打者の一打で入った点",
    "二塁打": "二塁打＝一打で二塁まで進んだ安打",
    "盗塁": "盗塁＝打撃を伴わずに次の塁を奪うこと",
    "四球": "四球＝ボール4つで一塁へ。打率には影響しない",
    "ゲーム差": "ゲーム差＝首位に追いつくのに必要な勝敗の差",
    "ワイルドカード": "ワイルドカード＝地区1位以外で進出する枠",
    "xG": "xG＝その形からゴールになる確率を積み上げた数字",
    "クリーンシート": "クリーンシート＝無失点で終えること",
}

# 1つの画面に出すのは1つだけ。2つ出すと、どちらも読まれない。
# 先に出てきた方ではなく、この順で優先する(説明の要る度合いの順)。
PRIORITY = ["xG", "WHIP", "OPS", "防御率", "ワイルドカード", "ゲーム差",
            "クリーンシート", "自責", "二塁打", "盗塁", "四球",
            "奪三振", "打点"]


def note_for(text: str, used: set = None) -> str:
    """
    その画面に出す説明を1つ返す。無ければ空。

    used に既に出した用語を入れておくと、同じ説明を繰り返さない。
    1本の動画で「OPSとは」を3回出しても意味が無い。
    """
    if not text:
        return ""
    for key in PRIORITY:
        if key in text and not (used and key in used):
            if used is not None:
                used.add(key)
            return NOTES[key]
    return ""
